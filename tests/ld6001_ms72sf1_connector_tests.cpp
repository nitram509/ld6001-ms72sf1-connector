#include <cassert>
#include <cstdint>
#include <iostream>
#include <vector>

#include "../ld6001_ms72sf1_connector.h"

static void push_le16(std::vector<uint8_t>& frame, int16_t value) {
    const auto u = static_cast<uint16_t>(value);
    frame.push_back(static_cast<uint8_t>(u & 0xFF));
    frame.push_back(static_cast<uint8_t>((u >> 8) & 0xFF));
}

static void test_ld6001_ms72sf1_parse() {
    hilink::Ld6001Parser parser;

    // example bytes from the documentation
    std::vector<uint8_t> frame = {
 0x01, 0x02, 0x03, 0x04,  0x05, 0x06, 0x07, 0x08,  0xA0, 0x00, 0x00, 0x00,  0xCD, 0x01, 0x00, 0x00,  0x01, 0x00, 0x00, 0x00,  0x00, 0x00, 0x00,
 0x00, 0x02, 0x00, 0x00,  0x00, 0x80, 0x00, 0x00,  0x00, 0x00, 0x00, 0x00,  0x00, 0x00, 0x00, 0x00,  0x00, 0xBE, 0x36, 0xD8,  0xBE, 0xCD, 0xB6,
 0xDC, 0x3E, 0x26, 0xC0,  0x87, 0x3F, 0x00, 0x00,  0x00, 0x00, 0x00, 0x00,  0x00, 0x00, 0x00, 0x00,  0x00, 0x00, 0x00, 0x00,  0x00, 0x00, 0x01,
 0x00, 0x00, 0x00, 0xC6,  0x36, 0x2E, 0xBF, 0xD3,  0xBF, 0xF2, 0xBF, 0xB6,  0x75, 0x9F, 0x3F, 0x00,  0x00, 0x00, 0x00, 0x00,  0x00, 0x00, 0x00,
 0x00, 0x00, 0x00, 0x00,  0x00, 0x00, 0x00, 0x00,  0x02, 0x00, 0x00, 0x00,  0xF4, 0xD1, 0x12, 0x3E,  0xE1, 0xE9, 0x99, 0x3F,  0x3F, 0x33, 0x8E, 0x3F,
 0x00, 0x00, 0x00, 0x00,  0x00, 0x00, 0x00, 0x00,  0x00, 0x00, 0x00, 0x00,  0x00, 0x00, 0x00, 0x00,  0x03, 0x00, 0x00, 0x00,  0x8E, 0xF1, 0x38,
 0xBB, 0xFB, 0xB9, 0x52,  0xBF, 0xEE, 0xBE, 0x02,  0x40, 0x00, 0x00, 0x00,  0x00, 0x00, 0x00, 0x00,  0x00, 0x00, 0x00, 0x00,
    };

    const auto result = parser.parse(frame.data(), frame.size());

    assert(result.size() == 1);
    assert(result[0].targetId == hilink::Ld6001Parser::SensorTarget::TARGET_1);
    assert(result[0].x == 10);
    assert(result[0].y == 20);
    assert(result[0].speed == 30);
    assert(result[0].resolution == 40);
    assert(result[0].valid);
}

int main() {
    test_ld6001_ms72sf1_parse();
    std::cout << "All tests passed\n";
    return 0;
}
